// Fails when any installed production dependency uses a license outside the allow-list.
// Also writes THIRD_PARTY_LICENSES.md with `--write`.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const ALLOWED = new Set([
  'MIT',
  'MIT-0',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'Apache-2.0',
  'BlueOak-1.0.0',
  'CC0-1.0',
  'CC-BY-4.0',
  'Python-2.0',
  'Unlicense',
]);

/** SPDX expressions like "(MIT OR Apache-2.0)" pass when at least one alternative is allowed. */
function isAllowed(expression) {
  const alternatives = expression.replace(/[()]/g, '').split(/\s+OR\s+/i);
  return alternatives.some((alt) => alt.split(/\s+AND\s+/i).every((part) => ALLOWED.has(part.trim())));
}

const raw = execSync('pnpm licenses list --json --prod -r', {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const byLicense = JSON.parse(raw);

const violations = [];
const rows = [];
for (const [license, packages] of Object.entries(byLicense)) {
  for (const pkg of packages) {
    if (pkg.name.startsWith('complexeditor') || pkg.name === 'demo') continue;
    rows.push({ name: pkg.name, versions: pkg.versions.join(', '), license, author: pkg.author ?? '' });
    if (!isAllowed(license)) violations.push(`${pkg.name}@${pkg.versions.join(',')}: ${license}`);
  }
}

if (process.argv.includes('--write')) {
  rows.sort((a, b) => a.name.localeCompare(b.name));
  const body = rows.map(
    (r) => `| ${r.name} | ${r.versions} | ${r.license} | ${r.author.replace(/\|/g, '/')} |`,
  );
  writeFileSync(
    'THIRD_PARTY_LICENSES.md',
    [
      '# Third-party licenses',
      '',
      'Production dependencies of this repository (generated by `pnpm licenses:check --write`).',
      '',
      '| Package | Version | License | Author |',
      '|---|---|---|---|',
      ...body,
      '',
    ].join('\n'),
  );
}

if (violations.length > 0) {
  console.error('Disallowed licenses found:\n' + violations.map((v) => `  - ${v}`).join('\n'));
  process.exit(1);
}
console.log(`License check passed (${rows.length} packages).`);
