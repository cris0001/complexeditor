export function UiIcon({
  name,
  size = 16,
  className,
}: {
  name: string | undefined;
  size?: number;
  className?: string;
}) {
  const Component = (name && UI_ICONS[name]) || Square;
  return (
    <Component size={size} className={className} aria-hidden="true" focusable="false" strokeWidth={1.75} />
  );
}
