/**
 * Resolves editor UI strings: built-in `pl`/`en`, a full custom dictionary via `dictionaries`,
 * and single-key `overrides`. Unknown locales fall back to English.
 */
export function getEditorMessages(
  locale = 'en',
  overrides?: Partial<EditorMessages>,
  dictionaries?: Record<string, Partial<EditorMessages>>,
): EditorMessages {
  const lang = locale.toLowerCase().split('-')[0]!;
  const builtIn = (editorMessages as Record<string, Partial<EditorMessages>>)[lang] ?? {};
  return {
    ...editorMessages.en,
    ...builtIn,
    ...dictionaries?.[locale],
    ...dictionaries?.[lang],
    ...overrides,
  };
}
